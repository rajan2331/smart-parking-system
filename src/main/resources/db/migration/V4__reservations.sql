-- Reservations: a driver books a specific spot for a time window.
-- btree_gist lets an exclusion constraint combine "same spot" (=) with "time ranges overlap" (&&).
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE reservations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL,
    vehicle_id          BIGINT       NOT NULL,
    parking_spot_id     BIGINT       NOT NULL,
    start_time          TIMESTAMP(6) NOT NULL,
    end_time            TIMESTAMP(6) NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    parking_session_id  BIGINT,
    created_at          TIMESTAMP(6),

    CONSTRAINT fk_reservations_user    FOREIGN KEY (user_id)            REFERENCES users (id),
    CONSTRAINT fk_reservations_vehicle FOREIGN KEY (vehicle_id)         REFERENCES vehicles (id),
    CONSTRAINT fk_reservations_spot    FOREIGN KEY (parking_spot_id)    REFERENCES parking_spot (id),
    CONSTRAINT fk_reservations_session FOREIGN KEY (parking_session_id) REFERENCES parking_sessions (id),
    CONSTRAINT uk_reservations_session UNIQUE (parking_session_id),
    CONSTRAINT reservations_status_check CHECK (status IN ('CONFIRMED', 'CHECKED_IN', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT reservations_time_check   CHECK (end_time > start_time),

    -- No two live reservations for the same spot may overlap. '[)' ranges: back-to-back is fine.
    CONSTRAINT ex_reservations_spot_overlap EXCLUDE USING gist (
        parking_spot_id WITH =,
        tsrange(start_time, end_time) WITH &&
    ) WHERE (status IN ('CONFIRMED', 'CHECKED_IN')),

    -- A vehicle can't hold two overlapping live reservations (on different spots).
    CONSTRAINT ex_reservations_vehicle_overlap EXCLUDE USING gist (
        vehicle_id WITH =,
        tsrange(start_time, end_time) WITH &&
    ) WHERE (status IN ('CONFIRMED', 'CHECKED_IN'))
);

-- Lookups: "my reservations", "upcoming reservations for a spot", and the no-show expiry job.
CREATE INDEX ix_reservations_user_status  ON reservations (user_id, status);
CREATE INDEX ix_reservations_spot_start   ON reservations (parking_spot_id, start_time);
CREATE INDEX ix_reservations_status_start ON reservations (status, start_time);
