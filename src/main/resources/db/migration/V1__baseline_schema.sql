-- Baseline: the schema as it existed when Flyway was introduced (previously created by Hibernate ddl-auto).
-- Existing databases are marked as already at V1 (spring.flyway.baseline-on-migrate), so this only runs on a fresh DB.

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6),
    email       VARCHAR(255) NOT NULL,
    mobile      VARCHAR(255) NOT NULL,
    name        VARCHAR(255),
    password    VARCHAR(255) NOT NULL,
    role        VARCHAR(20)  NOT NULL DEFAULT 'USER',
    CONSTRAINT uk_users_email  UNIQUE (email),
    CONSTRAINT uk_users_mobile UNIQUE (mobile),
    CONSTRAINT users_role_check CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE vehicles (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    color         VARCHAR(255),
    created_at    TIMESTAMP(6),
    plate_number  VARCHAR(255) NOT NULL,
    type          VARCHAR(255),
    user_id       BIGINT NOT NULL,
    CONSTRAINT uk_vehicles_plate_number UNIQUE (plate_number),
    CONSTRAINT fk_vehicles_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE parking_spot (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   TIMESTAMP(6),
    spot_number  VARCHAR(255) NOT NULL,
    status       VARCHAR(255) NOT NULL,
    type         VARCHAR(255) NOT NULL,
    CONSTRAINT uk_parking_spot_spot_number UNIQUE (spot_number),
    CONSTRAINT parking_spot_status_check CHECK (status IN ('AVAILABLE', 'OCCUPIED', 'MAINTENANCE')),
    CONSTRAINT parking_spot_type_check   CHECK (type IN ('STANDARD', 'HANDICAPPED', 'EV'))
);

CREATE TABLE parking_rates (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hourly_rate  NUMERIC(10, 2) NOT NULL,
    spot_type    VARCHAR(255)   NOT NULL,
    CONSTRAINT uk_parking_rates_spot_type UNIQUE (spot_type),
    CONSTRAINT parking_rates_spot_type_check CHECK (spot_type IN ('STANDARD', 'HANDICAPPED', 'EV'))
);

CREATE TABLE parking_sessions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_time       TIMESTAMP(6) NOT NULL,
    exit_time        TIMESTAMP(6),
    status           VARCHAR(255) NOT NULL,
    parking_spot_id  BIGINT NOT NULL,
    vehicle_id       BIGINT NOT NULL,
    parking_fee      NUMERIC(10, 2),
    CONSTRAINT parking_sessions_status_check CHECK (status IN ('ACTIVE', 'COMPLETED')),
    CONSTRAINT fk_parking_sessions_spot    FOREIGN KEY (parking_spot_id) REFERENCES parking_spot (id),
    CONSTRAINT fk_parking_sessions_vehicle FOREIGN KEY (vehicle_id)      REFERENCES vehicles (id)
);
